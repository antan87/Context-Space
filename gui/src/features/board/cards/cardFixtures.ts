/** What a card needs from the page around it on the Board: the actions, the card being read, and the notes on commits. */
export function CardContexts({ now, reading = null, actions = FIXTURE_ACTIONS, children }: { now: Date; reading?: string | null; actions?: BoardActions; children: ReactNode }) {
  return createElement(
    BoardActionsContext.Provider,
    { value: actions },
    createElement(
      BoardReadingContext.Provider,
      { value: reading },
      createElement(CommitNotesContext.Provider, { value: fixtureCommitNotes(now) }, children),
    ),
  );
}

/** `CardContexts` inside a React Flow provider, for a card drawn on its own (the golden test draws them this way). */
export function CardProviders({ now, reading = null, children }: { now: Date; reading?: string | null; children: ReactNode }) {
  return createElement(ReactFlowProvider, null, createElement(CardContexts, { now, reading, children }));
}

export function nodeProps<TNode extends Node>(
  id: string,
  type: TNode['type'],
  data: TNode['data'],
  size?: { width?: number; height?: number },
): NodeProps<TNode> {
  return {
    id,
    data,
    type: (type ?? '') as NonNullable<TNode['type']>,
    selected: false,
    zIndex: 1,
    isConnectable: false,
    positionAbsoluteX: 0,
    positionAbsoluteY: 0,
    dragging: false,
    draggable: false,
    selectable: false,
    deletable: false,
    ...size,
  } as NodeProps<TNode>;
}

/** A card to draw: which kind it is, the component and its props, and the id of the card the reader shows (when it is this one). */
export interface CardFixture {
  key: string;
  /** The node kind in `OVERVIEW_NODE_TYPES` or `AREA_NODE_TYPES`. */
  kind: string;
  Component: ComponentType<NodeProps>;
  props: NodeProps;
  reading: string | null;
}

function fx<TNode extends Node>(
  key: string,
  kind: string,
  Component: ComponentType<NodeProps<TNode>>,
  props: NodeProps<TNode>,
  reading: string | null = null,
): CardFixture {
  return { key, kind, Component: Component as unknown as ComponentType<NodeProps>, props: props as unknown as NodeProps, reading };
}

/** The same card with some of its data changed, under a new key (and its own id, so ids stay unique on one page). */
function variant(fixtures: CardFixture[], from: string, key: string, data: Record<string, unknown>, options: { reading?: boolean } = {}): CardFixture {
  const base = fixtures.find((fixture) => fixture.key === from);
  if (!base) throw new Error(`No fixture ${from}`);
  const id = `${base.props.id}~${key}`;
  return {
    ...base,
    key,
    props: { ...base.props, id, data: { ...(base.props.data as Record<string, unknown>), ...data } } as NodeProps,
    reading: options.reading ? id : null,
  };
}

